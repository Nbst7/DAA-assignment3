"""Write tests/my_cases.jsonl (inputs), my_cases_actual.jsonl (real outputs) and CASES.md.

Run from the repository root:
    python tests/write_cases.py
    python tools/run.py --input tests/my_cases.jsonl      # launcher prints the same actual results
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from my_cases import HAND_CASES  # noqa: E402


def dumps(value):
    return json.dumps(value, separators=(",", ":"))


def main():
    requests = []
    labels = []
    for case in HAND_CASES:
        if case["request"]["task"] == "kruskal":              # same input for both MST algorithms
            requests.append(case["request"])
            labels.append((case, "kruskal"))
            requests.append(dict(case["request"], task="prim"))
            labels.append((case, "prim"))
        else:
            requests.append(case["request"])
            labels.append((case, case["request"]["task"]))

    data = "".join(dumps(r) + "\n" for r in requests)
    with open(os.path.join(HERE, "my_cases.jsonl"), "w", encoding="utf-8") as f:
        f.write(data)

    proc = subprocess.run([sys.executable, os.path.join(ROOT, "src", "Python", "main.py")],
                          input=data, capture_output=True, text=True, encoding="utf-8", timeout=30)
    if proc.returncode:
        raise SystemExit(proc.stderr)
    lines = proc.stdout.splitlines()
    with open(os.path.join(HERE, "my_cases_actual.jsonl"), "w", encoding="utf-8") as f:
        f.write(proc.stdout)

    rows = ["# Own test cases: inputs, expected answers, actual outputs", "",
            "Generated by `python tests/write_cases.py`. `expected` lists only unique fields; witnesses",
            "(edge ids, order, parent edges, SCC labels) are validated by `tests/oracles.py`, see",
            "`tests/test_algorithms.py`.", ""]
    for (case, task), line in zip(labels, lines):
        rows += [f"## {case['name']} ({task})", "",
                 f"- **Why:** {case['why']}",
                 f"- **Input:** `{dumps(dict(case['request'], task=task))}`",
                 f"- **Expected:** `{dumps(case['expected'])}`",
                 f"- **Actual:** `{line}`", ""]
    with open(os.path.join(HERE, "CASES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(rows))
    print(f"wrote {len(requests)} requests")


if __name__ == "__main__":
    main()
